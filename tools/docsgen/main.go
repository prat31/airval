// Command docsgen prints the evaluator reference (Markdown) generated from evaluators.Catalog().
//
//	go run ./tools/docsgen > docs/evaluators-reference.md
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/prat31/airval/internal/evaluators"
)

type schema struct {
	Type        string             `json:"type"`
	Title       string             `json:"title"`
	Description string             `json:"description"`
	Enum        []any              `json:"enum"`
	Default     any                `json:"default"`
	Minimum     *float64           `json:"minimum"`
	Maximum     *float64           `json:"maximum"`
	Properties  map[string]*schema `json:"properties"`
	Required    []string           `json:"required"`
	Order       []string           `json:"x-order"`
	Items       *schema            `json:"items"`
}

func main() {
	cat := evaluators.Catalog()
	w := os.Stdout
	fmt.Fprint(w, "<!-- Generated by `go run ./tools/docsgen`. Do not edit by hand. -->\n\n")
	fmt.Fprint(w, "# Evaluator reference\n\n")
	fmt.Fprintf(w, "Every evaluator kind registered in this build (%d kinds), generated from `evaluators.Catalog()`. ", len(cat))
	fmt.Fprint(w, "For guidance on choosing evaluators see [evaluators.md](evaluators.md).\n\n")
	fmt.Fprint(w, "Each Suite attaches evaluators with a weight, a threshold, a severity and an apply-to scope; the per-kind **default threshold** is used when the Suite sets none. ")
	fmt.Fprint(w, "Config objects are strict: unknown fields are rejected.\n\n")

	fmt.Fprint(w, "| Kind | Category | Cost | Default threshold |\n|---|---|---|---|\n")
	for _, k := range cat {
		fmt.Fprintf(w, "| [`%s`](#%s) | %s | %s | %s |\n", k.Kind, k.Kind, k.Category, k.Cost.String(), num(k.DefaultThreshold))
	}
	fmt.Fprintln(w)

	lastCat := ""
	for _, k := range cat {
		if k.Category != lastCat {
			lastCat = k.Category
			fmt.Fprintf(w, "## %s evaluators\n\n", strings.ToUpper(lastCat[:1])+lastCat[1:])
		}
		fmt.Fprintf(w, "### %s\n\n", k.Kind)
		fmt.Fprintf(w, "**%s** · group `%s` · cost `%s` · default threshold `%s`\n\n", k.Name, k.Group, k.Cost.String(), num(k.DefaultThreshold))
		if k.Description != "" {
			fmt.Fprintf(w, "%s\n\n", k.Description)
		}
		var at []string
		for _, a := range k.ApplyTo {
			at = append(at, "`"+string(a)+"`")
		}
		fmt.Fprintf(w, "- Apply to: %s\n", strings.Join(at, ", "))
		if len(k.Requires) > 0 {
			var rq []string
			for _, r := range k.Requires {
				rq = append(rq, "`"+r+"`")
			}
			fmt.Fprintf(w, "- Requires: %s\n", strings.Join(rq, ", "))
		}
		if k.PromptVersion != "" {
			fmt.Fprintf(w, "- Judge prompt version: `%s`\n", k.PromptVersion)
		}
		fmt.Fprintln(w)
		var s schema
		if err := json.Unmarshal(k.ConfigSchema, &s); err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", k.Kind, err)
			os.Exit(1)
		}
		rows := flatten("", &s)
		if len(rows) == 0 {
			fmt.Fprint(w, "No configuration.\n\n")
			continue
		}
		fmt.Fprint(w, "| Field | Type | Required | Default | Description |\n|---|---|---|---|---|\n")
		for _, r := range rows {
			fmt.Fprintln(w, r)
		}
		fmt.Fprintln(w)
	}
}

func num(f float64) string {
	return strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.4f", f), "0"), ".")
}

func flatten(prefix string, s *schema) []string {
	names := s.Order
	if len(names) == 0 {
		for n := range s.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
	}
	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}
	var rows []string
	for _, n := range names {
		p := s.Properties[n]
		if p == nil {
			continue
		}
		name := prefix + n
		typ := p.Type
		if typ == "" {
			typ = "any"
		}
		if typ == "array" && p.Items != nil && p.Items.Type != "" {
			typ = p.Items.Type + "[]"
		}
		desc := p.Description
		if desc == "" {
			desc = p.Title
		}
		enum := p.Enum
		if p.Items != nil && len(enum) == 0 {
			enum = p.Items.Enum
		}
		if len(enum) > 0 {
			var e []string
			for _, v := range enum {
				e = append(e, fmt.Sprintf("`%v`", v))
			}
			desc += " One of: " + strings.Join(e, ", ") + "."
		}
		if p.Minimum != nil || p.Maximum != nil {
			var b []string
			if p.Minimum != nil {
				b = append(b, "min "+num(*p.Minimum))
			}
			if p.Maximum != nil {
				b = append(b, "max "+num(*p.Maximum))
			}
			desc += " (" + strings.Join(b, ", ") + ")"
		}
		def := ""
		if p.Default != nil {
			b, _ := json.Marshal(p.Default)
			def = "`" + string(b) + "`"
		}
		r := "no"
		if req[n] {
			r = "yes"
		}
		rows = append(rows, fmt.Sprintf("| `%s` | %s | %s | %s | %s |", name, typ, r, def, esc(strings.TrimSpace(desc))))
		if p.Type == "object" && len(p.Properties) > 0 {
			rows = append(rows, flatten(name+".", p)...)
		}
		if p.Type == "array" && p.Items != nil && p.Items.Type == "object" {
			rows = append(rows, flatten(name+"[].", p.Items)...)
		}
	}
	return rows
}

func esc(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.ReplaceAll(s, "\n", " ")
}
